/**
 * CommandCodeAdapter — Command Code CLI (`command-code acp`) via ACP.
 *
 * Command Code ships a stdio Agent Client Protocol server, so this adapter
 * mirrors {@link ./CursorAdapter} / {@link ./GrokAdapter}: one adapter per
 * configured instance, an Effect factory that captures its services at
 * construction, and a canonical `ProviderRuntimeEvent` stream for the UI.
 *
 * Command Code exposes five permission modes over ACP
 * (`default`, `auto-accept`, `plan`, `dont-ask`, `bypass`), which map onto
 * AgentTunnel's `RuntimeMode` plus the plan interaction mode. Approval
 * requests are surfaced to the user except in `full-access`, where the agent's
 * `bypass` mode normally prevents them and any that still arrive are
 * auto-approved.
 *
 * @module CommandCodeAdapter
 */

